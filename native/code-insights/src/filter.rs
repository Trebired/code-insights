use globset::{Glob, GlobMatcher};
use ignore::overrides::{Override, OverrideBuilder};
use ignore::Match;
use std::path::Path;

const GENERATED_NAMES: &[&str] = &[
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb",
    "Cargo.lock", "composer.lock", "Gemfile.lock", "poetry.lock", "Pipfile.lock", "go.sum", "flake.lock",
];
const GENERATED_SUFFIXES: &[&str] = &[".min.js", ".min.css", ".min.mjs", ".js.map", ".css.map", ".map", ".pb.go", "_pb2.py"];
const GENERATED_MARKERS: &[&str] = &["@generated", "Code generated", "DO NOT EDIT", "This file is automatically generated", "auto-generated"];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Exclusion {
    Documentation,
    Generated,
    Vendored,
}

struct AttributeRule {
    matcher: GlobMatcher,
    attribute: String,
    value: Option<String>,
}

pub struct Filter {
    documentation: Override,
    rules: Vec<AttributeRule>,
    vendor: Override,
}

fn override_with(add: fn(OverrideBuilder) -> OverrideBuilder) -> Override {
    add(OverrideBuilder::new("/")).build().unwrap_or_else(|_| Override::empty())
}

fn ignored(matcher: &Override, path: &str) -> bool {
    matches!(matcher.matched(Path::new(path), false), Match::Ignore(_))
}

fn attribute_glob(pattern: &str) -> Option<GlobMatcher> {
    let trimmed = pattern.trim_end_matches('/');
    let anchored = trimmed.contains('/');
    let base = trimmed.trim_start_matches('/');
    let glob = if anchored { base.to_string() } else { format!("**/{}", base) };
    let glob = if pattern.ends_with('/') { format!("{}/**", glob) } else { glob };
    Glob::new(&glob).ok().map(|value| value.compile_matcher())
}

fn parse_attribute(token: &str) -> (String, Option<String>) {
    if let Some(name) = token.strip_prefix('-') {
        return (name.to_string(), Some("false".to_string()));
    }
    if let Some((name, value)) = token.split_once('=') {
        return (name.to_string(), Some(value.to_string()));
    }
    (token.to_string(), Some("true".to_string()))
}

impl Filter {
    pub fn new(gitattributes: Option<&str>) -> Self {
        let mut rules = Vec::new();
        for line in gitattributes.unwrap_or("").lines().map(str::trim) {
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut tokens = line.split_whitespace();
            let Some(pattern) = tokens.next() else { continue };
            let Some(matcher) = attribute_glob(pattern) else { continue };
            for token in tokens.filter(|token| token.trim_start_matches('-').starts_with("linguist-")) {
                let (attribute, value) = parse_attribute(token);
                rules.push(AttributeRule { matcher: matcher.clone(), attribute, value });
            }
        }
        Filter {
            documentation: override_with(hyperpolyglot::filters::add_documentation_override),
            rules,
            vendor: override_with(hyperpolyglot::filters::add_vendor_override),
        }
    }

    fn attribute(&self, path: &str, name: &str) -> Option<String> {
        let mut found = None;
        for rule in self.rules.iter().filter(|rule| rule.attribute == name) {
            if rule.matcher.is_match(path) || dir_prefix_matches(&rule.matcher, path) {
                found = rule.value.clone();
            }
        }
        found
    }

    pub fn language_override(&self, path: &str) -> Option<String> {
        self.attribute(path, "linguist-language").map(|value| value.replace('_', " "))
    }

    pub fn exclusion_by_path(&self, path: &str) -> Option<Exclusion> {
        if let Some(value) = self.attribute(path, "linguist-vendored") {
            return if value == "true" { Some(Exclusion::Vendored) } else { None };
        }
        if self.attribute(path, "linguist-generated").as_deref() == Some("true") {
            return Some(Exclusion::Generated);
        }
        if self.attribute(path, "linguist-documentation").as_deref() == Some("true") {
            return Some(Exclusion::Documentation);
        }
        let name = path.rsplit('/').next().unwrap_or(path);
        if path.split('/').any(|part| part == "node_modules") {
            return Some(Exclusion::Vendored);
        }
        if GENERATED_NAMES.contains(&name) || GENERATED_SUFFIXES.iter().any(|suffix| name.ends_with(suffix)) {
            return Some(Exclusion::Generated);
        }
        if ignored(&self.vendor, path) {
            return Some(Exclusion::Vendored);
        }
        if ignored(&self.documentation, path) {
            return Some(Exclusion::Documentation);
        }
        None
    }

    pub fn generated_by_content(&self, path: &str, text: &str) -> bool {
        if self.attribute(path, "linguist-generated").as_deref() == Some("false") {
            return false;
        }
        let head: String = text.lines().take(5).collect::<Vec<_>>().join("\n");
        GENERATED_MARKERS.iter().any(|marker| head.contains(marker))
    }
}

fn dir_prefix_matches(matcher: &GlobMatcher, path: &str) -> bool {
    let mut prefix = String::new();
    for part in path.split('/') {
        if !prefix.is_empty() {
            prefix.push('/');
        }
        prefix.push_str(part);
        if prefix.len() < path.len() && matcher.is_match(&prefix) {
            return true;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn excludes_vendored_generated_and_documentation() {
        let filter = Filter::new(None);
        assert_eq!(filter.exclusion_by_path("node_modules/a/index.js"), Some(Exclusion::Vendored));
        assert_eq!(filter.exclusion_by_path("web/dist/app.js"), Some(Exclusion::Vendored));
        assert_eq!(filter.exclusion_by_path("bun.lock"), Some(Exclusion::Generated));
        assert_eq!(filter.exclusion_by_path("public/app.min.js"), Some(Exclusion::Generated));
        assert_eq!(filter.exclusion_by_path("docs/guide.md"), Some(Exclusion::Documentation));
        assert_eq!(filter.exclusion_by_path("src/app.ts"), None);
    }

    #[test]
    fn gitattributes_override_defaults() {
        let attributes = "third_party/** linguist-vendored\ndist/ -linguist-vendored\n*.gen.ts linguist-generated\n*.tpl linguist-language=HTML";
        let filter = Filter::new(Some(attributes));
        assert_eq!(filter.exclusion_by_path("third_party/x/y.c"), Some(Exclusion::Vendored));
        assert_eq!(filter.exclusion_by_path("dist/app.js"), None);
        assert_eq!(filter.exclusion_by_path("src/api.gen.ts"), Some(Exclusion::Generated));
        assert_eq!(filter.language_override("views/page.tpl").as_deref(), Some("HTML"));
    }

    #[test]
    fn spots_generated_headers() {
        let filter = Filter::new(None);
        assert!(filter.generated_by_content("a.go", "// Code generated by protoc. DO NOT EDIT.\npackage a"));
        assert!(!filter.generated_by_content("a.go", "package a"));
    }
}
